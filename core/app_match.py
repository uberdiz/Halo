"""
core/app_match.py

"What do I use on HalOS instead of this Windows app?" answered from a curated table (data/app_map.json,
generated by tools/dev/gen_app_map.py) before any store search. Name matching alone missed apps that do
have a Linux build (Google Antigravity, for one) and called drivers and runtimes "can't be migrated".

    lookup("Antigravity (User)")  -> Curated(kind="native", targets=["aur:antigravity-bin", "url:..."], ...)

kind:  native       there is a Linux version
       wine         the Windows version runs with Wine/Proton
       web          use the web app
       alternative  no Linux version; a named replacement is suggested
       none         nothing equivalent
       not_needed   drivers, runtimes, antivirus: nothing to bring, and not counted as a failure
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass, field
from functools import lru_cache
from pathlib import Path
from typing import Dict, List, Optional, Tuple

MAP_PATH = Path(__file__).resolve().parents[1] / "data" / "app_map.json"
KINDS = ("native", "wine", "web", "alternative", "none", "not_needed")
KIND_LABEL = {"native": "Works on HalOS", "wine": "Works with Wine or Proton", "web": "Web app",
              "alternative": "Alternative suggested", "none": "No match", "not_needed": "Not needed"}
# target prefix -> core.store source
STORE_SOURCE = {"featured": "featured", "repo": "repo", "flatpak": "flathub", "aur": "aur", "winget": "windows"}


@dataclass
class Curated:
    name: str
    kind: str
    targets: List[str] = field(default_factory=list)
    alternative: str = ""
    why: str = ""
    confidence: float = 1.0         # 1.0 exact name or id, 0.9 a listed other name, 0.7 a prefix/contains pattern
    matched_by: str = ""

    def store_target(self) -> Optional[Tuple[str, str]]:
        """(core.store source, id) for the first target the Store can install, or None."""
        for t in self.targets:
            prefix, _, value = t.partition(":")
            if prefix in STORE_SOURCE and value:
                return STORE_SOURCE[prefix], value
        return None

    def link(self) -> str:
        """The official download or web app, when the table gives one."""
        return next((t[4:] for t in self.targets if t.startswith("url:")), "")


def plain(s: str) -> str:
    """Lower case, version numbers, architectures and "(User)" style suffixes dropped."""
    s = re.sub(r"\((user|x64|x86|64-bit|32-bit|machine[^)]*)\)", " ", s.lower())
    s = re.sub(r"\b(x64|x86|64-bit|32-bit)\b|\bversion\b|\bv?\d+(\.\d+)+\w*\b", " ", s)
    return re.sub(r"\s+", " ", s).strip(" -")


@lru_cache(maxsize=4)
def _table(path: str):
    try:
        apps = json.loads(Path(path).read_text(encoding="utf-8")).get("apps", [])
    except (OSError, ValueError):
        return {}, {}, []
    exact: Dict[str, dict] = {}
    ids: Dict[str, dict] = {}
    patterns: List[Tuple[str, dict]] = []
    for e in apps:
        if e.get("kind") not in KINDS or not e.get("name"):
            continue
        exact.setdefault(plain(e["name"]), e)
        for m in e.get("match", []):
            if "*" in m:
                patterns.append((m, e))
            else:
                exact.setdefault(plain(m), e)
        for key in ("winget", "choco"):
            for i in e.get(key, []):
                ids.setdefault(i.lower(), e)
    return exact, ids, patterns


def _pattern_hit(pattern: str, name: str) -> bool:
    body = pattern.strip("*")
    if not body:
        return False
    if pattern.startswith("*") and pattern.endswith("*"):
        return body in name
    if pattern.endswith("*"):
        return name.startswith(body)
    return name.endswith(body)


def lookup(name: str, winget_id: str = "", path: Optional[Path] = None) -> Optional[Curated]:
    """The curated answer for a Windows app name (and its winget/Chocolatey id when known), or None."""
    exact, ids, patterns = _table(str(path or MAP_PATH))
    n = plain(name)
    hit, how, conf = None, "", 0.0
    if winget_id and winget_id.lower() in ids:
        hit, how, conf = ids[winget_id.lower()], "package id", 1.0
    elif n in exact:
        e = exact[n]
        hit, how, conf = e, "name", 1.0 if plain(e["name"]) == n else 0.9
    else:
        for pattern, e in patterns:
            if _pattern_hit(pattern, n) or _pattern_hit(pattern, name.lower()):
                hit, how, conf = e, f"pattern {pattern}", 0.7
                break
    if hit is None:
        return None
    return Curated(hit["name"], hit["kind"], list(hit.get("targets", [])), hit.get("alternative", ""),
                   hit.get("why", ""), conf, how)


def count() -> int:
    return len(json.loads(MAP_PATH.read_text(encoding="utf-8")).get("apps", [])) if MAP_PATH.exists() else 0
